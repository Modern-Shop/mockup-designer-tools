const catalogs: Record<DemoLanguage, Record<DemoKey, string>> = { en, fa, de };

export function demoText(language: DemoLanguage, key: DemoKey, vars: Record<string, string> = {}): string {
  let text = catalogs[language][key];
  // Values are bidi-isolated so Latin product names stay in place inside Persian sentences.
  for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(`⁨${value}⁩`);
  return text;
}
